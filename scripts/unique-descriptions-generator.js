function extractShortModel(name) {
  let res = name.split(':')[0].trim();
  res = res
    .replace(/^Жатка зернова прямого комбайнування\s*/i, '')
    .replace(/^Жатка зернобобова\s*/i, '')
    .replace(/^Жатка універсальна\s*/i, '')
    .replace(/^Картоплесаджалка\s*/i, '')
    .replace(/\s*Картоплесаджалка$/i, '')
    .replace(/^Овочезбиральний комбайн\s*/i, '')
    .replace(/^Картоплезбиральний комбайн\s*/i, '')
    .replace(/^Комбайн для збирання картоплі та цибулі\s*/i, '')
    .replace(/^Подрібнювач бадилля\s*/i, '')
    .replace(/\s*подрібнювач бадилля$/i, '')
    .replace(/^Гичкоподрібнювач[^\w]*/i, '')
    .replace(/^Копачка для цибулі[^\w]*/i, '')
    .replace(/^Автоматична кліпсаторна машина\s*/i, '')
    .replace(/^Автоматизоване очищення цибулі\s*/i, '')
    .replace(/^Інспекційний стіл для цибулі\s*/i, '')
    .replace(/^Машина для обрізання пера цибулі\s*/i, '')
    .replace(/^Наповнювач ящиків та коробок\s*/i, '')
    .replace(/^Мішконаповнювач\s*/i, '')
    .replace(/^Окучник для картоплі\s*/i, '')
    .replace(/^Модуль для сортування овочів\s*/i, '')
    .replace(/^Машина для сухого очищення овочів\s*/i, '')
    .replace(/^Приймальний бункер\s*/i, '')
    .replace(/^Причипна косарка цибулі\s*/i, '')
    .replace(/^Підбирач картоплі, цибулі\s*/i, '')
    .replace(/^Плита для картоплесаджалки\s*/i, '')
    .replace(/^Приводний пас\s*/i, '')
    .replace(/^Транспортер\s*/i, '')
    .replace(/^Жатки для комбайнів\s*/i, 'Жатки зернові')
    .trim();
  
  return res || name;
}

